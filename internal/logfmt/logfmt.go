// Package logfmt задаёт соглашение об усечении uid и префиксах модулей в логах шлюза.
//
// Соглашение:
//   - uid всегда усекается до 8 символов: выравнивание со строками chat (internal/server/logging.go uidPrefix),
//     в строке лога остаются только первые 8 символов uid. Полный uid можно найти в data/state.json (у 54 номеров нет коллизий 8-символьных префиксов).
//   - префиксы модулей: у четырёх типов расписания есть естественные префиксы (travel/activity/checkin/keepalive), они сохраняются;
//     остальному добавляется префикс [mod] в квадратных скобках вида [pool]/[auth]/[server], уже имеющиеся у redisstore/session сохраняются.
//   - семантика уровней: обычный ход идёт без пометки уровня (для краткости); подозрительные/пониженные/ошибочные строки помечаются префиксом WARN:/ERR:.
//
// Пакет не тянет логгер, а даёт только helper усечения UID8, чтобы пакеты не писали голое [:8] (защита от выхода за границы на uid короче 8).
package logfmt

// UID8 возвращает первые 8 символов uid; пустой uid возвращает "-" (выравнивание с server.uidPrefix).
//
// Для строк логов расписания и вне расписания: превращает <task> <full-uid>: ... в <task> <uid8>: ...
// Полный uid остаётся в state.json для разбора, в логах 8 символов достаточно для однозначного поиска.
func UID8(uid string) string {
	if uid == "" {
		return "-"
	}
	if len(uid) > 8 {
		return uid[:8]
	}
	return uid
}
